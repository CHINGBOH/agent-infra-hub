#!/usr/bin/env python3
"""Documentation generator for agent-infra-hub.

Derives living documentation from source-of-truth artifacts:

  - tools/agent_kb.py  → CLI reference (argparse introspection)
  - catalog.json       → resource path validation
  - 09-agent-infra-catalog/catalog.yaml → candidate repo ↔ filesystem audit
  - All *.md           → cross-link validation

Outputs land under docs/_generated/ and docs/reference/. The aim is that
whenever code (CLI signatures, file paths, catalog entries) changes,
`make docs` regenerates derived docs so committed docs never drift.

Usage:
  python tools/docs_gen.py all          # regenerate every derived doc
  python tools/docs_gen.py cli          # CLI reference only
  python tools/docs_gen.py links        # markdown link audit only
  python tools/docs_gen.py catalog      # catalog ↔ filesystem audit only
  python tools/docs_gen.py check        # regenerate to tempdir, diff vs committed (CI)

Standard library only — no external deps required.
"""

from __future__ import annotations

import argparse
import importlib.util
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from contextlib import redirect_stdout
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS = REPO_ROOT / "docs"
GENERATED = DOCS / "_generated"
REFERENCE = DOCS / "reference"

WARNING_BANNER = (
    "<!-- AUTO-GENERATED by tools/docs_gen.py — DO NOT EDIT BY HAND. "
    "Run `make docs` to regenerate. -->\n"
)

# Directories to skip when scanning markdown links.
SKIP_DIRS = {
    ".git",
    "node_modules",
    "data",
    "__pycache__",
    ".venv",
    "venv",
    "dist",
    "build",
    # Third-party clones documented separately; their internal cross-links
    # are not our concern.
    "09-agent-infra-catalog",
}

# Specific path prefixes (relative to REPO_ROOT) to skip — typically verbatim
# copies of upstream documentation that contain external link conventions
# (absolute /en/docs/... paths, sibling files we don't own).
SKIP_PATH_PREFIXES = (
    "skill-research/04-writing-guide/anthropic-best-practices.md",
    "skill-research/05-examples/",
)


def _vendored_roots() -> set[Path]:
    """Auto-detect vendored third-party clones (directories containing .git)."""
    roots: set[Path] = set()
    repo_git = REPO_ROOT / ".git"
    for git_dir in REPO_ROOT.rglob(".git"):
        if not git_dir.is_dir():
            continue
        if git_dir == repo_git:
            continue
        roots.add(git_dir.parent)
    return roots


