REPO_ENTRY_RE = re.compile(r"^\s*-\s+name:\s*(.+?)\s*$")


def audit_catalog() -> Path:
    issues: list[str] = []
    notes: list[str] = []

    # 1. catalog.json — every resource.path must exist (or be url).
    cj_path = REPO_ROOT / "catalog.json"
    catalog_json_resource_count = 0
    cj_missing: list[str] = []
    if cj_path.exists():
        data = json.loads(cj_path.read_text(encoding="utf-8"))
        for res in data.get("resources", []):
            catalog_json_resource_count += 1
            p = res.get("path")
            if not p:
                continue
            if not (REPO_ROOT / p).exists():
                cj_missing.append(f"{res.get('id', '?')} → {p}")
    else:
        notes.append("catalog.json not found at repo root.")

    # 2. catalog.yaml repositories — each `name` should correspond to a
    #    clone under 09-agent-infra-catalog/<category>/<basename>.
    cy_path = REPO_ROOT / "09-agent-infra-catalog" / "catalog.yaml"
    catalog_yaml_repos: list[str] = []
    cy_missing: list[str] = []
    if cy_path.exists():
        for line in cy_path.read_text(encoding="utf-8").splitlines():
            m = REPO_ENTRY_RE.match(line)
            if m:
                catalog_yaml_repos.append(m.group(1))
        for full in catalog_yaml_repos:
            basename = full.split("/")[-1]
            # find any directory ending in /basename inside 09-agent-infra-catalog
            matches = list((REPO_ROOT / "09-agent-infra-catalog").glob(f"*/{basename}"))
            if not matches:
                cy_missing.append(full)

    GENERATED.mkdir(parents=True, exist_ok=True)
    out = [
        WARNING_BANNER,
        "# Catalog ↔ Filesystem Audit",
        "",
        f"_Generated {_utc_today()} by `tools/docs_gen.py catalog`._",
        "",
        "## catalog.json",
        "",
        f"- Resources declared: **{catalog_json_resource_count}**",
        f"- Missing on disk: **{len(cj_missing)}**",
        "",
    ]
    if cj_missing:
        out += ["### Missing paths", ""]
        out += [f"- `{m}`" for m in cj_missing]
        out.append("")
    out += [
        "## 09-agent-infra-catalog/catalog.yaml",
        "",
        f"- Candidate repositories declared: **{len(catalog_yaml_repos)}**",
        f"- Not yet cloned locally: **{len(cy_missing)}**",
        "",
    ]
    if cy_missing:
        out += [
            "### Declared but not present on disk",
            "",
            "_(These are `metadata_first` entries — expected until promoted.)_",
            "",
        ]
        out += [f"- `{m}`" for m in cy_missing]
        out.append("")
    if notes:
        out += ["## Notes", ""] + [f"- {n}" for n in notes] + [""]

    path = GENERATED / "catalog-fs-report.md"
    path.write_text("\n".join(out), encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _utc_today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def _ensure_generated_readme() -> Path:
    GENERATED.mkdir(parents=True, exist_ok=True)
    path = GENERATED / "README.md"
    if not path.exists():
        path.write_text(
            WARNING_BANNER
            + "# `docs/_generated/` — Auto-Generated Reports\n\n"
            "All files in this directory are produced by `tools/docs_gen.py`.\n"
            "Do not hand-edit. Run `make docs` (or `python tools/docs_gen.py all`) to regenerate.\n\n"
            "| File | Source of truth | Producer |\n"
            "|------|-----------------|----------|\n"
            "| `cli-help.md` | `tools/agent_kb.py` argparse | `docs_gen.py cli` |\n"
            "| `cli-signatures.json` | `tools/agent_kb.py` argparse | `docs_gen.py cli` |\n"
            "| `link-report.md` | All repository `*.md` files | `docs_gen.py links` |\n"
            "| `catalog-fs-report.md` | `catalog.json` + `09-agent-infra-catalog/catalog.yaml` | `docs_gen.py catalog` |\n",
            encoding="utf-8",
        )
    return path


# ---------------------------------------------------------------------------
# Check mode (CI)
# ---------------------------------------------------------------------------

def check_in_place() -> int:
    """Run all generators in a temp scratch area and diff vs committed."""
    global GENERATED, REFERENCE
    original_generated = GENERATED
    original_reference = REFERENCE
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        GENERATED = tmp_path / "_generated"
        REFERENCE = tmp_path / "reference"
        generate_cli_reference()
        audit_links()
        audit_catalog()

        diff_failures: list[str] = []
        for src in GENERATED.rglob("*"):
            if not src.is_file():
                continue
            rel = src.relative_to(GENERATED)
            committed = original_generated / rel
            if not committed.exists() or committed.read_bytes() != src.read_bytes():
                diff_failures.append(str(original_generated / rel))
        for src in REFERENCE.rglob("*"):
            if not src.is_file():
                continue
            rel = src.relative_to(REFERENCE)
            committed = original_reference / rel
            if not committed.exists() or committed.read_bytes() != src.read_bytes():
                diff_failures.append(str(original_reference / rel))

    GENERATED = original_generated
    REFERENCE = original_reference

    if diff_failures:
        print("DOC DRIFT — the following committed docs are stale:", file=sys.stderr)
        for f in diff_failures:
            print(f"  - {f}", file=sys.stderr)
        print("Run `make docs` and commit the result.", file=sys.stderr)
        return 1
    print("✅ All generated docs are up to date.")
    return 0


# ---------------------------------------------------------------------------
# Entrypoint
# ---------------------------------------------------------------------------

def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "task",
        choices=["all", "cli", "links", "catalog", "check"],
        help="Which generator to run.",
    )
    args = parser.parse_args(argv)

    if args.task == "check":
        return check_in_place()

    produced: list[Path] = []
    if args.task in ("all", "cli"):
        produced += generate_cli_reference()
    if args.task in ("all", "links"):
        produced.append(audit_links())
    if args.task in ("all", "catalog"):
        produced.append(audit_catalog())
    if args.task == "all":
        produced.append(_ensure_generated_readme())

    for p in produced:
        print(f"wrote {p.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
